export type FieldType =
  | 'text'
  | 'textarea'
  | 'number'
  | 'money'
  | 'date'
  | 'select'
  | 'boolean'
  | 'member'
  | 'pet'
  | 'room'
  | 'box'
  | 'tags'
  | 'rating'
  | 'media'
  | 'phone'
  | 'email'
  | 'url'
  | 'images'
  | 'time'
  | 'members'
  | 'address'
  | 'zip';

export interface Option {
  value: string;
  label: string;
}

export interface FieldDef {
  key: string;
  label: string;
  type: FieldType;
  options?: Option[];
  placeholder?: string;
  help?: string;
  required?: boolean;
  section?: string;
  /** For 'address' and 'zip' fields: sibling field keys to auto-fill from the lookup. */
  fill?: AddressFill;
}

export interface AddressFill {
  street?: string;
  city?: string;
  state?: string;
  zip?: string;
  lat?: string;
  lng?: string;
}

export interface EntitySchema {
  table: TableName;
  singular: string;
  plural: string;
  icon: string;
  titleField: string;
  fields: FieldDef[];
}

